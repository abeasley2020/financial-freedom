// Writes docs/cards.md: every profession and card, grouped by deck, with the
// numbers and both texts, for a one-sitting realism review.
//
//   node scripts/cards-catalog.mjs
//
// Reads the JSON in packages/shared/src/data directly. The JSON is validated
// by @ff/shared at load and by its tests; this script only formats it. The
// totalExpenses column repeats the spec's liability percents (student 1,
// car 2, credit 3, floored) for display only.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const data = (path) => JSON.parse(readFileSync(join(root, 'packages/shared/src/data', path), 'utf8'));

const professions = data('professions.json');
const decks = [
  ['Small deals', data('cards/small-deals.json')],
  ['Big deals', data('cards/big-deals.json')],
  ['Market', data('cards/market.json')],
  ['Life Choices', data('cards/life-choices.json')],
  ['Setback', data('cards/setback.json')],
];

const PAYMENT_PERCENT = { student: 1, car: 2, credit: 3 };
const money = (n) => `${n < 0 ? '-' : ''}$${Math.abs(n).toLocaleString('en-US')}`;
const monthly = (n) => `${n < 0 ? '-' : '+'}$${Math.abs(n).toLocaleString('en-US')}/mo`;
const kids = (ok) => (ok ? 'kids: yes' : 'kids: no');
const tags = (principles) => principles.join(' ');

const out = [];
const line = (s = '') => out.push(s);

line('# Freedom Loop cards and professions');
line();
line('Generated by `node scripts/cards-catalog.mjs` from `packages/shared/src/data`. Do not edit by hand; edit the JSON and rerun.');
line();
line('Money is whole dollars. "Return on cash" is twelve months of cash flow divided by the down payment, shown only to judge realism; the game never uses it.');
line();
line(`Totals: ${String(professions.length)} professions, ${decks.map(([name, cards]) => `${String(cards.length)} ${name.toLowerCase()}`).join(', ')}.`);
line();

line('## Professions');
line();
line('| Profession | Salary | Base expenses | Starting debt | Debt payments | Total expenses | Monthly cash flow | Starting cash |');
line('| --- | ---: | ---: | --- | ---: | ---: | ---: | ---: |');
for (const p of professions) {
  const payments = p.startingLiabilities.reduce((sum, l) => sum + Math.floor((l.principal * PAYMENT_PERCENT[l.kind]) / 100), 0);
  const total = p.baseExpenses + payments;
  const debt = p.startingLiabilities.map((l) => `${l.kind} ${money(l.principal)}`).join(', ');
  const flow = p.salary - total;
  const share = Math.round((flow * 100) / p.salary);
  line(`| ${p.name} | ${money(p.salary)} | ${money(p.baseExpenses)} | ${debt} | ${money(payments)} | ${money(total)} | ${money(flow)} (${String(share)}%) | ${money(p.startingCash)} |`);
}
line();
line('Sources and reasoning: `docs/content-notes.md`.');
line();

function effectText(e) {
  switch (e.kind) {
    case 'payCash':
      return `pay ${money(e.amount)}`;
    case 'gainCash':
      return `gain ${money(e.amount)}`;
    case 'addLoan':
      return `${e.loanKind} loan ${money(e.principal)} at ${money(e.monthlyPayment)}/mo`;
    case 'addSubscription':
      return `subscription ${money(e.monthlyCost)}/mo`;
    case 'investGrowth':
      return `invest ${money(e.amount)} in ${e.assetType} (grows ${String(e.growthPercent)}%/mo, pays ${String(e.payoutPercent)}%)`;
    case 'repayLargestLoan':
      return `pay down largest loan by up to ${money(e.amount)}`;
    case 'offerBuyout':
      return `buyer offers ${String(e.percentOfPurchasePrice)}% of purchase price for one`;
    case 'forceSale':
      return `must sell at ${String(e.percentOfPurchasePrice)}% of purchase price`;
    case 'changeCashFlow':
      return `cash flow ${monthly(e.delta)} each`;
    case 'splitShares':
      return `shares split ${String(e.ratio)} for 1`;
    case 'changeMarketValue':
      return `market value ${e.percent < 0 ? '' : '+'}${String(e.percent)}%`;
    default:
      throw new Error(`unknown effect ${JSON.stringify(e)}`);
  }
}

function dealNumbers(c) {
  if (c.type === 'stock') {
    const dividend = c.dividendPerShare ? `, dividend ${money(c.dividendPerShare)}/share/mo` : ', no dividend';
    return `stock, ${String(c.sharesAvailable)} shares at ${money(c.priceRange.min)} to ${money(c.priceRange.max)}${dividend}`;
  }
  if (c.growthPercent !== undefined) {
    return `${c.type}, minimum ${money(c.price)}, grows ${String(c.growthPercent)}%/mo, pays ${String(c.payoutPercent)}% of value/mo`;
  }
  const ret = c.downPayment > 0 ? `, return on cash ${String(Math.round((c.monthlyCashFlow * 1200) / c.downPayment))}%/yr` : '';
  return `${c.type}, price ${money(c.price)}, down ${money(c.downPayment)}, mortgage ${money(c.mortgage)}, cash flow ${monthly(c.monthlyCashFlow)}${ret}`;
}

for (const [name, cards] of decks) {
  line(`## ${name} (${String(cards.length)})`);
  line();
  for (const c of cards) {
    line(`### ${c.id} ${c.title}`);
    line();
    if (c.deck === 'smallDeals' || c.deck === 'bigDeals') line(`${dealNumbers(c)}. ${tags(c.principles)}. ${kids(c.kidsOk)}.`);
    if (c.deck === 'market') line(`${c.effects.map(effectText).join('; ')}. Applies to: ${c.appliesTo.join(', ')}. ${tags(c.principles)}. ${kids(c.kidsOk)}.`);
    if (c.deck === 'setback') line(`Pay ${money(c.cashCost)}${c.skipTurn ? ', skip next turn' : ''}. ${tags(c.principles)}.`);
    if (c.deck === 'lifeChoices') line(`${c.category}. ${tags(c.principles)}. ${kids(c.kidsOk)}.`);
    line();
    line(`- Adult: ${c.adultText}`);
    line(`- Kids: ${c.kidsText}`);
    if (c.deck === 'lifeChoices') {
      line();
      for (const o of c.options) {
        const effects = o.effects.length === 0 ? 'nothing changes' : o.effects.map(effectText).join(', ');
        line(`- **${o.label}** (${effects}; ${tags(o.principles)}; ${kids(o.kidsOk)})`);
        line(`  - Adult: ${o.adultText}`);
        line(`  - Kids: ${o.kidsText}`);
      }
    }
    line();
  }
}

writeFileSync(join(root, 'docs/cards.md'), out.join('\n'));
