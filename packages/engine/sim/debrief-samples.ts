// Writes docs/debrief-samples.md (Stage E): debriefs from three bot games,
// the winner and the last-placed player of each, at both reading levels, so
// Andre can judge whether the debrief teaches.
//
//   pnpm exec tsx packages/engine/sim/debrief-samples.ts
//
// The games are the first seeds from 20261023 that fit: a kids game with
// three or more players, a Wealth Builder vs Big Spender game, and a mixed
// standard game with three or more players that ends in an escape.

import { writeFileSync } from 'node:fs';

import { debriefText, PROFESSIONS, READING_LEVELS, type GameState } from '@ff/shared';

import { debrief } from '../src/debrief/debrief';
import { rankPlayers } from '../src/selectors';
import { STRATEGIES, STRATEGY_NAMES, type Strategy } from './bots';
import { playGameWithState, type GameRecord, type SimOptions } from './simulate';

interface Sample {
  readonly heading: string;
  readonly why: string;
  readonly options: SimOptions;
  readonly fits: (record: GameRecord) => boolean;
}

const base = { games: 1, seed: 20_261_023, maxTurns: 400, minPlayers: 2, maxPlayers: 4, strategies: STRATEGIES } as const;

const SAMPLES: readonly Sample[] = [
  { heading: 'Game 1: kids mode', why: 'a kids game with three or more players', options: { ...base, mode: 'kids' }, fits: (r) => r.players >= 3 },
  {
    heading: 'Game 2: Wealth Builder vs Big Spender',
    why: 'a two-player standard game, Wealth Builder against Big Spender',
    options: { ...base, mode: 'standard', minPlayers: 2, maxPlayers: 2, lineup: ['wealthBuilder', 'bigSpender'] },
    fits: () => true,
  },
  { heading: 'Game 3: mixed strategies', why: 'a standard game with three or more players that ends in an escape', options: { ...base, mode: 'standard' }, fits: (r) => r.players >= 3 && r.ending === 'escape' },
];

function find(sample: Sample): { readonly record: GameRecord; readonly state: GameState } {
  for (let seed = base.seed; seed < base.seed + 5_000; seed++) {
    const played = playGameWithState(seed, sample.options);
    if (sample.fits(played.record)) return played;
  }
  throw new Error(`no game fits: ${sample.why}`);
}

const professionName = (id: string): string => PROFESSIONS.find((p) => p.id === id)?.name ?? id;

function seatLabel(state: GameState, record: GameRecord, playerId: string): string {
  const index = state.players.findIndex((p) => p.id === playerId);
  const seat = record.seats[index];
  const strategy: Strategy | undefined = seat?.strategy;
  return `${professionName(seat?.professionId ?? '')} (${strategy === undefined ? '?' : STRATEGY_NAMES[strategy]})`;
}

function section(title: string, lines: readonly string[], empty: string): string[] {
  return [`**${title}**`, '', ...(lines.length === 0 ? [`- ${empty}`] : lines.map((l) => `- ${l}`)), ''];
}

function render(state: GameState, playerId: string): string[] {
  const out: string[] = [];
  for (const level of READING_LEVELS) {
    const d = debrief(state, playerId, level);
    const t = debriefText(d);
    out.push(`#### ${level === 'kids' ? 'Kids reading level' : 'Adult reading level'}`, '');
    out.push(...section('1. Result', [t.result], ''));
    out.push(...section(d.result.outcome === 'won' || d.result.outcome === 'escaped' ? '2. Why you won' : '2. Why you lost', t.drivers, 'No single decision stood out.'));
    out.push(...section('3. Decisions that helped', t.helped, 'None this game.'));
    out.push(...section('4. Decisions that hurt', t.hurt, 'None this game.'));
    out.push(...section('5. Next time, try', t.suggestions, 'Nothing to change: no decision hurt.'));
    out.push(...section('6. Money story', [t.moneyStory], ''));
    out.push(...section('7. Principles practiced', t.principles, 'None yet.'));
  }
  return out;
}

function main(): void {
  const lines: string[] = [
    '# Debrief samples',
    '',
    'Generated by `pnpm exec tsx packages/engine/sim/debrief-samples.ts` from three bot games on the Stage D content. For each game: the winner and the last-placed player, each at the kids and adult reading levels, in the spec\'s seven-section order. The question for Andre (Stage E gate): does it teach?',
    '',
    'Numbers come from `debrief()` in `packages/engine/src/debrief/`; the words come from the templates in `packages/shared/src/debriefText.ts`, which fill numbers in and never compute them. Kids numbers are rounded to $10.',
    '',
  ];
  for (const sample of SAMPLES) {
    const { record, state } = find(sample);
    const ranked = [...rankPlayers(state).map((p) => p.id), ...state.players.filter((p) => p.isOut).map((p) => p.id)];
    const winnerId = state.game.currentPlayerId;
    const loserId = [...ranked].reverse().find((id) => id !== winnerId) ?? ranked[0] ?? winnerId;
    const players = state.players.map((p) => seatLabel(state, record, p.id)).join(', ');
    lines.push(`## ${sample.heading}`, '');
    lines.push(`Seed ${String(record.seed)}, ${record.ending === 'escape' ? 'ended by escape' : record.ending === 'lastStanding' ? 'ended with one player left' : 'ended at the round limit'} in round ${String(record.rounds)}. Seats: ${players}. Chosen as the first seed that is ${sample.why}.`, '');
    for (const [role, id] of [['Winner', winnerId], ['Last place', loserId]] as const) {
      lines.push(`### ${role}: ${seatLabel(state, record, id)}`, '');
      lines.push(...render(state, id));
    }
  }
  const path = new URL('../../../docs/debrief-samples.md', import.meta.url);
  writeFileSync(path, lines.join('\n'), 'utf8');
  process.stderr.write(`debrief samples written to ${path.pathname}\n`);
}

main();
